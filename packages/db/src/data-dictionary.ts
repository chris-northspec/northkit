import type pg from 'pg';

// Schemas documented in docs/data-dictionary. pgboss belongs to the job queue
// library and is left out on purpose.
export const DOCUMENTED_SCHEMAS = ['public', 'core', 'register', 'movements', 'audit', 'reporting'] as const;

interface ColumnInfo {
  table: string;
  column: string;
  type: string;
  nullable: boolean;
  default: string | null;
  comment: string | null;
  references: string | null;
}

interface TableInfo {
  schema: string;
  name: string;
  kind: 'table' | 'partitioned table' | 'view';
  comment: string | null;
  rls: boolean;
  partitions: number;
  columns: ColumnInfo[];
}

export interface Dictionary {
  schemas: { name: string; comment: string | null }[];
  tables: TableInfo[];
  missing: string[];
}

/** Reads every table, view and column in the documented schemas with its COMMENT. */
export async function readDictionary(client: pg.Pool | pg.ClientBase): Promise<Dictionary> {
  const schemas = await client.query<{ name: string; comment: string | null }>(
    `SELECT n.nspname AS name, obj_description(n.oid, 'pg_namespace') AS comment
       FROM pg_namespace n WHERE n.nspname = ANY($1) ORDER BY array_position($1, n.nspname::text)`,
    [DOCUMENTED_SCHEMAS],
  );
  const tables = await client.query<{
    oid: number;
    schema: string;
    name: string;
    relkind: string;
    comment: string | null;
    rls: boolean;
    partitions: number;
  }>(
    `SELECT c.oid, n.nspname AS schema, c.relname AS name, c.relkind, obj_description(c.oid, 'pg_class') AS comment,
            c.relrowsecurity AS rls,
            (SELECT count(*)::int FROM pg_inherits i WHERE i.inhparent = c.oid) AS partitions
       FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = ANY($1) AND c.relkind IN ('r', 'p', 'v') AND NOT c.relispartition
      ORDER BY n.nspname, c.relname`,
    [DOCUMENTED_SCHEMAS],
  );
  const columns = await client.query<ColumnInfo & { oid: number }>(
    `SELECT a.attrelid::int AS oid, c.relname AS table, a.attname AS column,
            format_type(a.atttypid, a.atttypmod) AS type, NOT a.attnotnull AS nullable,
            pg_get_expr(d.adbin, d.adrelid) AS default, col_description(a.attrelid, a.attnum) AS comment,
            (SELECT format('%s.%s', fn.nspname, fc.relname)
               FROM pg_constraint fk
               JOIN pg_class fc ON fc.oid = fk.confrelid
               JOIN pg_namespace fn ON fn.oid = fc.relnamespace
              WHERE fk.conrelid = a.attrelid AND fk.contype = 'f' AND a.attnum = ANY (fk.conkey)
              ORDER BY array_length(fk.conkey, 1) LIMIT 1) AS references
       FROM pg_attribute a
       JOIN pg_class c ON c.oid = a.attrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace
       LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE n.nspname = ANY($1) AND c.relkind IN ('r', 'p', 'v') AND NOT c.relispartition
        AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attrelid, a.attnum`,
    [DOCUMENTED_SCHEMAS],
  );

  const kinds = { r: 'table', p: 'partitioned table', v: 'view' } as const;
  const result: TableInfo[] = tables.rows.map((t) => ({
    schema: t.schema,
    name: t.name,
    kind: kinds[t.relkind as keyof typeof kinds],
    comment: t.comment,
    rls: t.rls,
    partitions: t.partitions,
    columns: columns.rows.filter((c) => c.oid === t.oid).map(({ oid: _oid, ...c }) => c),
  }));

  const missing: string[] = [];
  for (const s of schemas.rows) if (!s.comment?.trim()) missing.push(`schema ${s.name}`);
  for (const t of result) {
    if (!t.comment?.trim()) missing.push(`table ${t.schema}.${t.name}`);
    for (const c of t.columns) {
      if (!c.comment?.trim()) missing.push(`column ${t.schema}.${t.name}.${c.column}`);
    }
  }
  return { schemas: schemas.rows, tables: result, missing };
}

const cell = (text: string | null) => (text ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

/** Renders the dictionary as Markdown files: README.md plus one file per schema. */
export function renderDictionary(dictionary: Dictionary): Map<string, string> {
  const files = new Map<string, string>();
  const header =
    '<!-- Generated by `pnpm db:docs` from the database COMMENTs. Do not edit by hand. -->\n\n';

  const index = [
    `${header}# Data dictionary\n`,
    'Every table and column, from the `COMMENT`s in the migrations (DB-14). Columns whose description starts with **[personal]** hold personal data (DB-13).\n',
    '| Schema | Purpose | Tables |',
    '| --- | --- | --- |',
    ...dictionary.schemas.map((s) => {
      const count = dictionary.tables.filter((t) => t.schema === s.name).length;
      return `| [\`${s.name}\`](${s.name}.md) | ${cell(s.comment)} | ${count} |`;
    }),
    '',
  ];
  files.set('README.md', index.join('\n'));

  for (const schema of dictionary.schemas) {
    const tables = dictionary.tables.filter((t) => t.schema === schema.name);
    const lines = [`${header}# Schema \`${schema.name}\`\n`, `${cell(schema.comment)}\n`];
    if (tables.length === 0) lines.push('No tables yet.\n');
    for (const t of tables) {
      const notes = [
        t.kind === 'view' ? 'view' : null,
        t.rls ? 'row-level security' : null,
        t.kind === 'partitioned table' ? 'partitioned by month' : null,
      ].filter(Boolean);
      lines.push(`## \`${t.schema}.${t.name}\`\n`);
      lines.push(`${cell(t.comment)}${notes.length ? ` _(${notes.join(', ')})_` : ''}\n`);
      lines.push('| Column | Type | Null | Default | References | Description |');
      lines.push('| --- | --- | --- | --- | --- | --- |');
      for (const c of t.columns) {
        lines.push(
          `| \`${c.column}\` | ${cell(c.type)} | ${c.nullable ? 'yes' : 'no'} | ${c.default ? `\`${cell(c.default)}\`` : ''} | ${c.references ? `\`${c.references}\`` : ''} | ${cell(c.comment)} |`,
        );
      }
      lines.push('');
    }
    files.set(`${schema.name}.md`, lines.join('\n'));
  }
  return files;
}
